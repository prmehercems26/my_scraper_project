app = Flask(__name__)

DATABASE_POOLER_HOST = "aws-0-eu-west-1.pooler.supabase.com"
DATABASE_POOLER_PORT = 6543
DESCRIPTION_MAX_LENGTH = 240


def is_allowed_supabase_url(value):
    if not isinstance(value, str) or len(value) > 255:
        return False
    try:
        parsed = urlparse(value)
        hostname = parsed.hostname
        port = parsed.port
    except ValueError:
        return False
    if parsed.username or parsed.password or parsed.query or parsed.fragment:
        return False
    if parsed.scheme == "https" and hostname:
        return (
            port is None
            and parsed.path in {"", "/"}
            and bool(re.fullmatch(r"[a-z0-9-]+\.supabase\.co", hostname))
        )
    return (
        parsed.scheme == "http"
        and hostname in {"localhost", "127.0.0.1"}
        and parsed.path in {"", "/"}
        and not parsed.query
        and not parsed.fragment
    )

def is_public_supabase_key(value):
    if not isinstance(value, str) or len(value) > 4096:
        return False
    if value.startswith("sb_publishable_"):
        return True

    parts = value.split(".")
    if len(parts) != 3:
        return False
    try:
        payload = parts[1] + "=" * (-len(parts[1]) % 4)
        claims = json.loads(base64.urlsafe_b64decode(payload))
        return claims.get("role") == "anon"
    except (ValueError, json.JSONDecodeError):
        return False

def ensure_table_exists(supabase_url, database_password):
    project_ref = urlparse(supabase_url).hostname.split(".")[0]
    with psycopg2.connect(
        host=DATABASE_POOLER_HOST,
        port=DATABASE_POOLER_PORT,
        dbname="postgres",
        user=f"postgres.{project_ref}",
        password=database_password,
        sslmode="require",
        connect_timeout=10
    ) as connection:
        with connection.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS public.books (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title TEXT NOT NULL,
                    price_gbp NUMERIC,
                    availability TEXT,
                    image_url TEXT,
                    book_url TEXT,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
                );
                ALTER TABLE public.books ADD COLUMN IF NOT EXISTS image_url TEXT;
                ALTER TABLE public.books ADD COLUMN IF NOT EXISTS book_url TEXT;
                ALTER TABLE public.books ENABLE ROW LEVEL SECURITY;
                GRANT USAGE ON SCHEMA public TO anon;
                GRANT INSERT ON TABLE public.books TO anon;
                GRANT USAGE, SELECT ON SEQUENCE public.books_id_seq TO anon;
                DO $$
                BEGIN
                    IF EXISTS (
                        SELECT 1 FROM pg_policies
                        WHERE schemaname = 'public'
                          AND tablename = 'books'
                          AND policyname = 'Allow demo book inserts'
                    ) THEN
                        ALTER POLICY "Allow demo book inserts"
                        ON public.books TO anon WITH CHECK (true);
                    ELSE
                        CREATE POLICY "Allow demo book inserts"
                        ON public.books FOR INSERT TO anon WITH CHECK (true);
                    END IF;
                END;
                $$;
                NOTIFY pgrst, 'reload schema';
            """)


def fetch_product_description(book_url):
    response = requests.get(book_url, timeout=10)
    response.raise_for_status()
    soup = BeautifulSoup(response.text, 'html.parser')
    description_heading = soup.find(id='product_description')
    paragraph = description_heading.find_next_sibling('p') if description_heading else None
    if not paragraph:
        return ''

    description = ' '.join(paragraph.get_text(' ', strip=True).split())
    if len(description) > DESCRIPTION_MAX_LENGTH:
        snippet = description[:DESCRIPTION_MAX_LENGTH - 3].rsplit(' ', 1)[0]
        description = (snippet or description[:DESCRIPTION_MAX_LENGTH - 3]) + '...'
    return description


@app.route('/')
def home():
    return render_template('index.html')

@app.route('/api/scrape', methods=['POST'])
def run_scraper():
    data = request.get_json(silent=True) or {}
    if not isinstance(data, dict):
        return jsonify({"success": False, "error": "Request body must be a JSON object"}), 400

    supabase_url = data.get("supabase_url", "")
    supabase_key = data.get("supabase_key", "")
    database_password = data.get("database_password", "")

    if isinstance(supabase_url, str):
        supabase_url = supabase_url.strip()
    if isinstance(supabase_key, str):
        supabase_key = supabase_key.strip()

    if not isinstance(database_password, str) or not database_password:
        return jsonify({"success": False, "error": "Enter your Supabase database password."}), 400
    if not is_allowed_supabase_url(supabase_url):
        return jsonify({"success": False, "error": "Enter a valid Supabase project URL."}), 400
    if not is_public_supabase_key(supabase_key):
        return jsonify({"success": False, "error": "Use a Supabase publishable key or legacy anon key, not a secret or service-role key."}), 400

    try:
        limit = int(data.get('limit', 5))
    except (TypeError, ValueError):
        return jsonify({"success": False, "error": "Limit must be a number"}), 400

    if limit < 1 or limit > 50:
        return jsonify({"success": False, "error": "Limit must be between 1 and 50"}), 400

    supabase = create_client(supabase_url, supabase_key)

    url = "https://books.toscrape.com/"
    response = requests.get(url, timeout=15)
    if response.status_code != 200:
        return jsonify({"success": False, "error": "Failed to fetch page"}), 500

    soup = BeautifulSoup(response.text, 'html.parser')
    books = soup.find_all('article', class_='product_pod')

    scraped_data = []
    for index, book in enumerate(books):
        if index >= limit:
            break

        title = book.h3.a['title']
        price = float(book.find('p', class_='price_color').text.replace('Â£', '').replace('£', ''))
        availability = book.find('p', class_='instock availability').text.strip()
        image = book.find('div', class_='image_container').find('img')
        relative_image_url = image['src'] if image else ''
        relative_book_url = book.h3.a['href']
        book_url = urljoin(url, relative_book_url)

        scraped_data.append({
            'title': title,
            'price_gbp': price,
            'availability': availability,
            'image_url': urljoin(url, relative_image_url),
            'book_url': book_url
        })

    if scraped_data:
        try:
            with ThreadPoolExecutor(max_workers=min(8, len(scraped_data))) as executor:
                descriptions = executor.map(
                    fetch_product_description,
                    [book['book_url'] for book in scraped_data]
                )
                for book, description in zip(scraped_data, descriptions):
                    book['description'] = description
        except requests.RequestException as error:
            app.logger.warning("Book description request failed: %s", error)
            return jsonify({
                "success": False,
                "error": "Could not fetch book descriptions. Please try again."
            }), 502

    if scraped_data:
        database_records = [
            {
                field: book[field]
                for field in ('title', 'price_gbp', 'availability', 'image_url', 'book_url')
            }
            for book in scraped_data
        ]
        try:
            # 1st attempt: Try to insert data immediately
            supabase.table("books").insert(database_records).execute()
        except Exception:
            # If the 1st attempt fails, unconditionally try to fix the database schema
            try:
                ensure_table_exists(supabase_url, database_password)
                # 2nd attempt: Insert data again now that columns exist
                supabase.table("books").insert(database_records).execute()

            except psycopg2.OperationalError as error:
                message = str(error).lower()
                app.logger.warning("Supabase database connection failed (%s): %s", error.pgcode or type(error).__name__, error)
                if error.pgcode == "28P01" or "password authentication failed" in message:
                    error_message = "The database password was rejected. Use the Postgres database password, not your Supabase account password."
                elif any(term in message for term in ("could not translate host", "connection timed out", "timeout expired", "network is unreachable", "no route to host", "could not connect to server")):
                    error_message = "Could not reach the Supabase transaction pooler. Check the project region, password, and outbound port 6543."
                else:
                    error_message = "Could not connect to the database. Check the project URL and database password."
                return jsonify({"success": False, "error": error_message}), 502

            except psycopg2.Error as error:
                app.logger.error("Supabase books table setup failed (%s): %s", error.pgcode or type(error).__name__, error)
                return jsonify({
                    "success": False,
                    "error": "Connected to the database, but could not create or configure public.books. Check the server terminal for the database error."
                }), 500

            except Exception as final_error:
                # If it still fails, send the exact error back to the frontend so you can see it
                return jsonify({
                    "success": False,
                    "error": f"Database updated, but insert still failed: {str(final_error)}"
                }), 500

    return jsonify({"success": True, "data": scraped_data})

if __name__ == '__main__':
    app.run(debug=True)